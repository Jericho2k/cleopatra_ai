-- Claims one of the creator's daily manual AI re-analysis slots atomically.
-- The advisory lock prevents simultaneous dashboard requests from exceeding
-- the limit. The UTC-day boundary makes the rule deterministic across workers.
create or replace function public.claim_vault_recategorization(
    p_creator_id uuid,
    p_media_id text,
    p_daily_limit integer default 5
)
returns table (used integer, remaining integer)
language plpgsql
security definer
set search_path = public
as $$
declare
    v_used integer;
begin
    perform pg_advisory_xact_lock(hashtext(p_creator_id::text));

    select count(*)::integer
      into v_used
      from public.vault_recategorization_events
     where creator_id = p_creator_id
       and created_at >= date_trunc('day', now() at time zone 'UTC') at time zone 'UTC';

    if v_used >= p_daily_limit then
        raise exception 'daily vault re-categorization limit reached'
            using errcode = 'P0001';
    end if;

    insert into public.vault_recategorization_events (creator_id, media_id)
    values (p_creator_id, p_media_id);

    v_used := v_used + 1;
    return query select v_used, greatest(p_daily_limit - v_used, 0);
end;
$$;

create or replace function public.vault_recategorization_usage(
    p_creator_id uuid,
    p_daily_limit integer default 5
)
returns table (used integer, remaining integer, daily_limit integer)
language sql
stable
security definer
set search_path = public
as $$
    with usage as (
        select count(*)::integer as used
          from public.vault_recategorization_events
         where creator_id = p_creator_id
           and created_at >= date_trunc('day', now() at time zone 'UTC') at time zone 'UTC'
    )
    select used, greatest(p_daily_limit - used, 0), p_daily_limit
      from usage;
$$;

-- These mutation/usage functions are backend-only. The dashboard reaches them
-- through the authenticated API; browser Supabase roles cannot claim quotas or
-- reconciliation leases directly.
revoke all on function public.claim_chat_reconciliation(uuid, integer)
    from public, anon, authenticated;
revoke all on function public.claim_vault_recategorization(uuid, text, integer)
    from public, anon, authenticated;
revoke all on function public.vault_recategorization_usage(uuid, integer)
    from public, anon, authenticated;

grant execute on function public.claim_chat_reconciliation(uuid, integer) to service_role;
grant execute on function public.claim_vault_recategorization(uuid, text, integer) to service_role;
grant execute on function public.vault_recategorization_usage(uuid, integer) to service_role;
