create or replace function public.claim_chat_reconciliation(
    p_creator_id uuid,
    p_min_interval_minutes integer default 10
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
    v_claimed uuid;
begin
    update public.creators
       set last_chat_reconcile_at = now()
     where id = p_creator_id
       and (
           last_chat_reconcile_at is null
           or last_chat_reconcile_at <= now() - make_interval(mins => greatest(p_min_interval_minutes, 1))
       )
    returning id into v_claimed;
    return v_claimed is not null;
end;
$$;

